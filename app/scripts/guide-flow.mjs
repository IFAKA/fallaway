// node scripts/guide-flow.mjs — click through the real-deck guide (setup, first zoom) and screenshot each stage.
import puppeteer from 'puppeteer-core'
import fs from 'node:fs'
fs.mkdirSync('/tmp/shots', { recursive: true })
const b = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--no-sandbox'] })
const p = await b.newPage()
await p.setViewport({ width: 1300, height: 1100 })
await p.goto('http://localhost:5199/', { waitUntil: 'networkidle0' })
await p.evaluate(() => localStorage.clear()); await p.reload({ waitUntil: 'networkidle0' })
const sleep = (t) => new Promise(r => setTimeout(r, t))
const click = (sel, text) => p.evaluate((sel, text) => { const e = [...document.querySelectorAll(sel)].find(e => e.textContent.trim() === text && !e.disabled); if (!e) throw new Error('no ' + sel + ' ' + text); e.click() }, sel, text)
const shot = (n) => p.screenshot({ path: `/tmp/shots/g${n}.png` })
await shot('0-intro'); await click('button', 'Start setup'); await shot('1-lock')
await click('.pbtn', '4♣'); await sleep(200); await shot('2-vault')
await click('button', 'Done — next')
for (const c of ['J♠', '2♦', '2♣', '10♣', 'Q♣']) await click('.pbtn', c)
await sleep(200); await shot('3-grid')
await click('.pbtn', '10♠'); await sleep(200); await shot('4-hide')
await click('button', 'Start playing'); await sleep(300); await shot('5-play')
await click('button', 'Zoom IN (pay 1)'); await sleep(200)
await p.evaluate(() => { const c = [...document.querySelectorAll('.hand .gcard')][0]; c.click() })
await sleep(300); await shot('6-spread-enter')
await click('.pbtn', '5♣'); await click('.pbtn', 'A♥'); await sleep(300); await shot('7-spread')
await b.close()

// node scripts/lap2.mjs — load a saved practice game that is already on lap 2 (zoom costs 2) and pay with two cards.
import puppeteer from 'puppeteer-core'
import fs from 'node:fs'
const saved = fs.readFileSync('/tmp/lap2.json', 'utf8')
const b = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--no-sandbox'] })
const p = await b.newPage()
await p.setViewport({ width: 1300, height: 1000 })
await p.evaluateOnNewDocument((saved) => { localStorage.setItem('zoom-mode', 'practice'); localStorage.setItem('zoom-seen-intro', '1'); localStorage.setItem('zoom-v1', saved) }, saved)
await p.goto('http://localhost:5199/', { waitUntil: 'networkidle0' })
const sleep = (t) => new Promise(r => setTimeout(r, t))
await sleep(1200)
const clickBtn = (text) => p.evaluate((text) => { const e = [...document.querySelectorAll('button')].find(e => e.textContent.includes(text) && !e.disabled); if (!e) throw new Error('no button ' + text); e.click() }, text)
await clickBtn('Zoom IN (pay 2)'); await sleep(300)
const clickPackCard = (k) => p.evaluate((k) => { const st = document.querySelector('.stage').getBoundingClientRect(); const cs = [...document.querySelectorAll('.stage .acard')].filter(e => e.getBoundingClientRect().y - st.y > 600); cs[k].click() }, k)
await clickPackCard(0); await clickPackCard(1); await sleep(300)
await p.screenshot({ path: '/tmp/shots/lap2-paying.png' })
await clickBtn('Confirm'); await sleep(1500)
await p.screenshot({ path: '/tmp/shots/lap2-spread.png' })
console.log(await p.evaluate(() => [...document.querySelectorAll('.log div')].map(e => e.textContent).slice(-3).join(' | ')))
await b.close()
